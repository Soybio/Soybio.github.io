#!/usr/bin/env python3
"""Write assets/js/seqdata.js: scientific constants for the Tools page, taken from Biopython.

Taking the tables from Biopython (instead of typing them) keeps the website results
identical to Biopython, which tools/validate_tools.py checks.

Run from the website folder:  python3 tools/build_seqdata.py
"""
import json
from pathlib import Path

import Bio
from Bio.Align import substitution_matrices
from Bio.Data import CodonTable, IUPACData
from Bio import Restriction
from Bio.SeqUtils import IsoelectricPoint, MeltingTemp, ProtParamData

ROOT = Path(__file__).resolve().parent.parent
ENZYMES = ["AatII", "AflII", "ApaI", "AscI", "AvrII", "BamHI", "BglII", "BsaI", "BbsI", "BsmBI", "ClaI",
           "DraI", "EcoRI", "EcoRV", "HindIII", "HpaI", "KpnI", "MluI", "NcoI", "NdeI", "NheI", "NotI",
           "NsiI", "PacI", "PstI", "SacI", "SacII", "SalI", "SapI", "ScaI", "SmaI", "SpeI", "SphI",
           "StuI", "XbaI", "XhoI", "XmaI"]

table = CodonTable.unambiguous_dna_by_id[1]  # Standard genetic code
blosum = substitution_matrices.load("BLOSUM62")
letters = "ARNDCQEGHILKMFPSTWYVBZX*"

data = {
    "source": f"Biopython {Bio.__version__}",
    "proteinWeights": IUPACData.protein_weights,   # average masses (Da), free amino acids
    "water": 18.0153,
    "kd": ProtParamData.kd,                        # Kyte & Doolittle (1982) hydropathy
    "diwv": ProtParamData.DIWV,                    # Guruprasad et al. (1990) instability weights
    "posPK": IsoelectricPoint.positive_pKs,
    "negPK": IsoelectricPoint.negative_pKs,
    "pKnterm": IsoelectricPoint.pKnterminal,
    "pKcterm": IsoelectricPoint.pKcterminal,
    "chargedAA": IsoelectricPoint.charged_aas,
    "nn": MeltingTemp.DNA_NN3,                     # Allawi & SantaLucia (1997) nearest neighbours
    "codons": table.forward_table,
    "stops": table.stop_codons,
    "starts": table.start_codons,
    "blosum62": {a: {b: blosum[a][b] for b in letters} for a in letters},
    # Common restriction enzymes: site, cut offsets (fst5, fst3), overhang, from REBASE via Biopython.
    "enzymes": [{"name": n, "site": str(getattr(Restriction, n).site), "fst5": getattr(Restriction, n).fst5,
                 "fst3": getattr(Restriction, n).fst3, "ovhg": getattr(Restriction, n).ovhg,
                 "pal": getattr(Restriction, n).is_palindromic()} for n in ENZYMES],
}

js = ("/* Generated by tools/build_seqdata.py from " + data["source"] + ". Do not edit by hand. */\n"
      "window.SoybioSeqData = " + json.dumps(data, separators=(",", ":")) + ";\n")
out = ROOT / "assets" / "js" / "seqdata.js"
out.write_text(js, encoding="utf-8")
print(f"{out.name}: {out.stat().st_size / 1e3:.1f} KB from {data['source']}")
